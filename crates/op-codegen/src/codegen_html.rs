pub struct Html;

impl Codegen for Html {
    fn target_label(&self) -> &'static str {
        "html"
    }

    fn generate(&self, doc: &PenDocument) -> String {
        self.generate_selection(doc, crate::root_nodes(doc).iter(), &Default::default())
    }
}

impl Html {
    pub(crate) fn generate_prepared(&self, doc: &PenDocument) -> String {
        let mut out = String::from("<!-- Generated by OpenPencil — codegen::Html -->\n<!DOCTYPE html>\n<html><head><meta charset=\"utf-8\"><meta name=\"viewport\" content=\"width=device-width,initial-scale=1\">");
        if let Some(name) = &doc.name {
            let _ = write!(out, "<title>{}</title>", html_escape(name));
        }
        let motion_css = codegen_motion_css::render(doc);
        if !motion_css.is_empty() {
            let _ = writeln!(out, "<style>\n{motion_css}</style>");
        }
        tokens::stylesheet(&mut out, doc);
        let fonts = crate::html_fonts::stylesheet(doc);
        if !fonts.is_empty() {
            let _ = writeln!(out, "<style data-op-fonts>{fonts}</style>");
        }
        out.push_str("</head>\n<body>\n");
        let roots = root_nodes(doc);
        for node in roots {
            emit(&mut out, node, 1, Parent::Canvas, roots.len() == 1);
        }
        out.push_str("</body></html>\n");
        out
    }
}

pub(super) fn emit_node_html(out: &mut String, node: &PenNode, depth: usize) {
    emit(out, node, depth, Parent::Canvas, false);
}

fn paint_color(color: &str, opacity: f32) -> String {
    let opacity = opacity.clamp(0.0, 1.0);
    if opacity < 1.0 {
        if let Some((r, g, b, a)) = parse_color(color) {
            return format!(
                "rgba({},{},{},{:.3})",
                (r * 255.).round(),
                (g * 255.).round(),
                (b * 255.).round(),
                a * opacity
            );
        }
    }
    let paint = if let Some(reference) = tokens::reference(color) {
        reference
    } else if tokens::safe_color(color) {
        color_to_css(color)
    } else {
        return "transparent".into();
    };
    if opacity < 1.0 {
        format!("color-mix(in srgb,{paint} {}%,transparent)", opacity * 100.)
    } else {
        paint
    }
}

fn shape_style(style: &mut String, node: &PenNode) {
    let is_text = matches!(node, PenNode::Text(_));
    let is_path = matches!(node, PenNode::Path(_));
    if !is_path {
        if let Some(fill) = node_fill_css(node) {
            let property = if is_text { "color" } else { "background" };
            let _ = write!(
                style,
                ";{property}:{}",
                paint_color(&fill, fills::first_solid_fill_opacity(node))
            );
        }
    }
    let mut shadows = Vec::new();
    // Canvas strokes paint over their box. CSS borders consume layout space,
    // moving every padded child and changing fill-container widths.
    if !is_path {
        if let Some((color, width)) = node_stroke_css(node) {
            if width > 0.0 {
                let color = paint_color(&color, fills::first_solid_stroke_opacity(node));
                shadows.push(format!("inset 0 0 0 {width}px {color}"));
            }
        }
    }
    for effect in fills::node_effects(node) {
        match effect {
            PenEffect::Shadow(s) if s.visible != Some(false) => {
                let prefix = if s.inner == Some(true) { "inset " } else { "" };
                shadows.push(format!(
                    "{prefix}{}px {}px {}px {}px {}",
                    s.offset_x,
                    s.offset_y,
                    s.blur,
                    s.spread,
                    paint_color(&s.color, 1.0)
                ));
            }
            PenEffect::Blur(b) if b.visible != Some(false) => {
                let _ = write!(style, ";filter:blur({}px)", b.radius);
            }
            PenEffect::BackgroundBlur(b) if b.visible != Some(false) => {
                let _ = write!(style, ";backdrop-filter:blur({}px)", b.radius);
            }
            _ => {}
        }
    }
    if !shadows.is_empty() {
        let _ = write!(style, ";box-shadow:{}", shadows.join(","));
    }
    let radius = layout::container(node)
        .and_then(|c| c.corner_radius.as_ref())
        .or_else(|| match node {
            PenNode::Image(n) => n.corner_radius.as_ref(),
            _ => None,
        });
    if matches!(node, PenNode::Ellipse(_)) {
        style.push_str(";border-radius:50%");
    } else if let Some(CornerRadius::PerCorner(r)) = radius {
        let _ = write!(
            style,
            ";border-radius:{}px {}px {}px {}px",
            r[0], r[1], r[2], r[3]
        );
    } else {
        let radius = emitted_corner_radius(node);
        if radius > 0.0 {
            let _ = write!(style, ";border-radius:{}px", fmt_num(radius));
        }
    }
    match &node.base().opacity {
        Some(NumberOrExpression::Number(n)) => {
            let _ = write!(style, ";opacity:{}", fmt_num(n.clamp(0.0, 1.0)));
        }
        Some(NumberOrExpression::Expression(s)) => {
            if let Some(opacity) = tokens::reference(s) {
                let _ = write!(style, ";opacity:{opacity}");
            }
        }
        None => {}
    }
    let base = node.base();
    let deg = crate::node_rotation_deg(node);
    if deg != 0.0 || base.flip_x == Some(true) || base.flip_y == Some(true) {
        let _ = write!(style, ";transform:rotate({}deg)", fmt_num(deg));
        if base.flip_x == Some(true) {
            style.push_str(" scaleX(-1)");
        }
        if base.flip_y == Some(true) {
            style.push_str(" scaleY(-1)");
        }
    }
}

fn vector(
    out: &mut String,
    node: &PenNode,
    path: &PathNode,
    attrs: &str,
    mut style: String,
    indent: &str,
) {
    let data = path.d.clone().filter(|d| !d.is_empty()).unwrap_or_else(|| {
        op_editor_core::path_edit::anchors_to_path_data(
            path.anchors.as_deref().unwrap_or_default(),
            path.closed.unwrap_or(false),
        )
    });
    let (x, y, w, h) = op_editor_core::svg_path_data_bounds(&data).unwrap_or((
        0.,
        0.,
        node.width_px().unwrap_or(1.) as f32,
        node.height_px().unwrap_or(1.) as f32,
    ));
    // Give a flat line a nonzero SVG viewport; overflow preserves its stroke
    // on both sides. The authored box in the outer layout stays otherwise exact.
    if path.width.is_none() || node.width_px() == Some(0.) {
        let _ = write!(style, ";width:{}px", w.max(1.));
    }
    if path.height.is_none() || node.height_px() == Some(0.) {
        let _ = write!(style, ";height:{}px", h.max(1.));
    }
    let _=write!(out,"{indent}<svg{attrs} xmlns=\"http://www.w3.org/2000/svg\" viewBox=\"{x} {y} {} {}\" preserveAspectRatio=\"none\" style=\"{};overflow:visible\"><path d=\"{}\"",
        if w>0. {w} else {1.}, if h>0. {h} else {1.}, html_escape(&style),html_escape(&data));
    let fill = node_fill_css(node)
        .map(|v| paint_color(&v, fills::first_solid_fill_opacity(node)))
        .unwrap_or_else(|| "none".into());
    let _ = write!(out, " fill=\"{}\"", html_escape(&fill));
    if matches!(path.fill_rule, Some(PathFillRule::Evenodd)) {
        out.push_str(" fill-rule=\"evenodd\"");
    }
    if let (Some(stroke), Some((color, width))) = (&path.stroke, node_stroke_css(node)) {
        let _ = write!(
            out,
            " stroke=\"{}\" stroke-width=\"{width}\" vector-effect=\"non-scaling-stroke\"",
            html_escape(&paint_color(
                &color,
                fills::first_solid_stroke_opacity(node)
            ))
        );
        match stroke.cap {
            Some(StrokeCap::Round) => out.push_str(" stroke-linecap=\"round\""),
            Some(StrokeCap::Square) => out.push_str(" stroke-linecap=\"square\""),
            _ => {}
        }
        match stroke.join {
            Some(StrokeJoin::Round) => out.push_str(" stroke-linejoin=\"round\""),
            Some(StrokeJoin::Bevel) => out.push_str(" stroke-linejoin=\"bevel\""),
            _ => {}
        }
        if let Some(pattern) = &stroke.dash_pattern {
            let _ = write!(
                out,
                " stroke-dasharray=\"{}\"",
                pattern
                    .iter()
                    .map(f32::to_string)
                    .collect::<Vec<_>>()
                    .join(" ")
            );
        }
        if let Some(offset) = stroke.dash_offset {
            let _ = write!(out, " stroke-dashoffset=\"{offset}\"");
        }
    }
    out.push_str(" /></svg>\n");
}

fn emit(out: &mut String, node: &PenNode, depth: usize, parent: Parent, standalone: bool) {
    if node_hidden(node) {
        return;
    }
    let indent = "  ".repeat(depth);
    let mut attrs = format!(" data-op-id=\"{}\"", html_escape(node.id_str()));
    if let Some(name) = &node.base().name {
        let _ = write!(attrs, " data-op-name=\"{}\"", html_escape(name));
    }
    attrs.push_str(&codegen_motion_css::data_attribute(node));
    let semantics = node.gestures_and_semantics().1;
    if let Some(label) = semantics.and_then(|s| s.label.as_deref()) {
        let _ = write!(attrs, " aria-label=\"{}\"", html_escape(label));
    }
    let button =
        matches!(semantics.and_then(|s| s.role), Some(SemanticRole::Button)) && node.is_container();
    let mut style = layout::geometry(node, parent, standalone);
    if button {
        attrs.push_str(" type=\"button\"");
        if matches!(node.base().enabled, Some(BoolOrExpression::Bool(false))) {
            attrs.push_str(" disabled");
        }
        style.push_str(";appearance:none;margin:0;border:0;padding:0;background:transparent;color:inherit;font:inherit");
    }
    shape_style(&mut style, node);
    layout::container_style(&mut style, node);
    style.push_str(&codegen_motion_css::inline_style(node));
    match node {
        PenNode::Path(path) => {
            vector(out, node, path, &attrs, style, &indent);
            return;
        }
        PenNode::Image(img) => {
            // The canvas samples an untransformed image with Skia's default
            // nearest filter. Browser smoothing blurs small type in cover art.
            let _ = write!(
                style,
                ";object-fit:{};image-rendering:pixelated",
                image_object_fit(node).expect("image fit")
            );
            let _ = writeln!(
                out,
                "{indent}<img src=\"{}\" alt=\"{}\"{attrs} style=\"{}\" />",
                html_escape(img.src.as_ref()),
    if fields::emit(out, node, &attrs, &style, &indent) {
        return;
    }
                html_escape(img.base.name.as_deref().unwrap_or_default()),
                html_escape(&style)
            );
            return;
        }
        PenNode::Text(n) => {
            text::style(&mut style, n);
            let _ = write!(
                out,
                "{indent}<span{attrs} style=\"{}\">",
                html_escape(&style)
            );
            text::body(out, n);
            out.push_str("</span>\n");
            return;
        }
        _ => {}
    }
    let tag = if button { "button" } else { "div" };
    let _ = write!(
        out,
        "{indent}<{tag}{attrs} style=\"{}\">",
        html_escape(&style)
    );
    if let Some(widget) = widget_markup(node) {
        out.push_str(&widget);
    } else {
        if let Some(nav) = tabs_nav_markup(node) {
            out.push_str(&nav);
        }
        let children = node_children(node);
        if !children.is_empty() {
            out.push('\n');
            for child in children {
                emit(out, child, depth + 1, layout::flow(node), false);
            }
            out.push_str(&indent);
        }
    }
    let _ = writeln!(out, "</{tag}>");
}

